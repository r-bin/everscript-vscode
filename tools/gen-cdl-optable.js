'use strict';

// Writes src/emulator/core/snes9x2005-wasm/source/cdl-optable.h from
// src/emulator/cdl/opcodes.js so the core's instruction lengths and flow
// kinds always match the disassembler's.
//   node tools/gen-cdl-optable.js

const fs = require('fs');
const path = require('path');
const { OPCODES, MODE_SIZE, flowKind, isStackOp } = require('../src/emulator/cdl/opcodes');

const OUT = path.join(__dirname, '..', 'src', 'emulator', 'core', 'snes9x2005-wasm', 'source', 'cdl-optable.h');

function render() {
    // bits 0-1: operand bytes; 0x04: +1 when M=0; 0x08: +1 when X=0;
    // 0x10: stack op; 0x20: indirect jump through a ROM/RAM pointer
    const info = OPCODES.map((o, op) => {
        const size = MODE_SIZE[o.mode];
        let v = size === 'M' ? 1 | 0x04 : size === 'X' ? 1 | 0x08 : size;
        if (isStackOp(op)) v |= 0x10;
        if (op === 0x6C || op === 0x7C || op === 0xDC || op === 0xFC) v |= 0x20;
        return v;
    });
    const flow = OPCODES.map((_, op) => flowKind(op));

    const hex = arr => arr.map(v => '0x' + v.toString(16).padStart(2, '0'))
        .reduce((rows, v, i) => { if (i % 16 === 0) rows.push([]); rows[rows.length - 1].push(v); return rows; }, [])
        .map(r => '   ' + r.join(', ')).join(',\n');

    const text = `/* Generated by tools/gen-cdl-optable.js from src/emulator/cdl/opcodes.js - do not edit. */
#ifndef CDL_OPTABLE_H
#define CDL_OPTABLE_H

#define CDL_OP_LEN_MASK 0x03
#define CDL_OP_M16      0x04
#define CDL_OP_X16      0x08
#define CDL_OP_STACK    0x10
#define CDL_OP_IJUMP    0x20

static const uint8_t CDL_OpInfo[256] = {
${hex(info)}
};

/* FLOW bits: 1 call, 2 jump, 4 conditional branch, 8 indirect */
static const uint8_t CDL_OpFlow[256] = {
${hex(flow)}
};

#endif
`;
    return text;
}

if (require.main === module) {
    fs.writeFileSync(OUT, render());
    console.log('wrote ' + path.relative(process.cwd(), OUT));
}

module.exports = { render, OUT };
