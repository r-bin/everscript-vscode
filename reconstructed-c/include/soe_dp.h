/*
 * soe_dp.h: direct page slots that always hold one thing, as offsets for DP8 and DP16. Slots reused for anything are named where
 * they are used (skill c-style).
 */
#ifndef SOE_DP_H
#define SOE_DP_H

#define DP_PARENT_ENTITY 0x4C       /* the entity the current child record belongs to */
#define DP_CHILD_RECORD  0x4E       /* byte offset of the current child record */

#endif
